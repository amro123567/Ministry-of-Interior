"""Emit the MySQL DDL script for the Correspondence Tracking System.

The application runs on SQLite by default and on MySQL through DATABASE_URL
(app.py, README "Run it"). models.py is the single definition of the schema;
this script renders it as the standalone DDL the SDD designs for -- InnoDB,
utf8mb4, explicit referential actions -- so the schema can be created on a
MySQL server without running the application, which is what a DBA doing a
production install actually needs.

Usage:  python schema/generate_mysql_ddl.py > schema/mysql_schema.sql
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sqlalchemy.schema import CreateTable, CreateIndex
from sqlalchemy.dialects import mysql

from app import app          # noqa: F401  -- binds the metadata
from extensions import db
import models as m           # noqa: F401

DIALECT = mysql.dialect()
DB_NAME = os.environ.get("CTS_DB_NAME", "civil_registry_db")

# SDD 6.6.2 / R-13: "Arabic names are frequently transcribed inconsistently
# (ال prefixes, hamza variants, ة/ه); exact-prefix matching will fail against
# real data, and a clerk who cannot find an existing citizen will create a
# duplicate record -- the worst possible outcome for a registry."
# MySQL 8 and MariaDB both refuse a CHECK constraint that references a column
# carrying a foreign key referential action ("Foreign key referential actions
# are prohibited on columns used in CHECK constraints"), and both refuse a
# non-deterministic function such as CURRENT_DATE inside one. SQLite accepts
# both and enforces these as CHECKs.
#
# The rule is not dropped on MySQL -- each of these is re-expressed as a
# BEFORE INSERT/UPDATE trigger in mysql_triggers.sql. Verified against
# MariaDB 10.11: emitting them as CHECK constraints makes CREATE TABLE fail
# outright, so the schema would not build at all.
CHECKS_NOT_VALID_ON_MYSQL = {
    "ck_citizens_dob_not_future",      # CURRENT_DATE is non-deterministic
    "ck_documents_soft_delete",        # references deleted_by  (FK action)
    "ck_guardianship_distinct",        # references *_citizen_id (FK actions)
    "ck_transfer_distinct_offices",    # references *_office_id  (FK actions)
    "ck_requests_rejection_reason",    # references rejected_by  (FK action)
}

FULLTEXT = [
    ("citizens", "ft_citizens_name_ar",
     "first_name_ar, middle_name_ar, last_name_ar",
     "Partial and fuzzy Arabic name matching (R-13). MySQL 8 only: the ngram "
     "parser does not exist in MariaDB, where this degrades to a plain "
     "FULLTEXT index that will not match sub-word fragments."),
]


def emit(line=""):
    print(line)


def main():
    emit("-- ====================================================================")
    emit("-- Correspondence Tracking System - Civil Registry")
    emit("-- MySQL 8 / InnoDB schema, generated from models.py")
    emit("--")
    emit("-- Generated by schema/generate_mysql_ddl.py. Do not hand-edit: change")
    emit("-- models.py and regenerate, or the two definitions will diverge.")
    emit("-- ====================================================================")
    emit()
    emit(f"CREATE DATABASE IF NOT EXISTS `{DB_NAME}`")
    emit("  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;")
    emit(f"USE `{DB_NAME}`;")
    emit()
    emit("SET FOREIGN_KEY_CHECKS = 0;")
    emit()

    for table in db.metadata.sorted_tables:
        dropped = [c for c in table.constraints
                   if getattr(c, "name", None) in CHECKS_NOT_VALID_ON_MYSQL]
        for c in dropped:
            table.constraints.discard(c)
        ddl = str(CreateTable(table).compile(dialect=DIALECT)).strip()
        for c in dropped:
            table.constraints.add(c)
            emit(f"-- {c.name}: enforced by trigger on MySQL, see mysql_triggers.sql")
        emit(f"-- {'-' * 68}")
        emit(f"{ddl};")
        emit()

    emit(f"-- {'=' * 68}")
    emit("-- Indexes - SDD 6.6")
    emit(f"-- {'=' * 68}")
    emit()
    for table in db.metadata.sorted_tables:
        for index in sorted(table.indexes, key=lambda i: i.name):
            emit(f"{str(CreateIndex(index).compile(dialect=DIALECT)).strip()};")
    emit()

    emit(f"-- {'=' * 68}")
    emit("-- Full-text indexes - SDD 6.6.2 / R-13")
    emit(f"-- {'=' * 68}")
    emit()
    for table, name, cols, why in FULLTEXT:
        emit(f"-- {why}")
        emit(f"CREATE FULLTEXT INDEX {name} ON {table} ({cols}) WITH PARSER ngram;")
        emit()

    emit("SET FOREIGN_KEY_CHECKS = 1;")
    emit()
    emit(open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "mysql_triggers.sql"), encoding="utf-8").read())


if __name__ == "__main__":
    main()
